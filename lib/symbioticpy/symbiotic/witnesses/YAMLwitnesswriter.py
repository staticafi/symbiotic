def get_hash(source):
    f = open(source, 'r', encoding='utf-8')
    hsh = hashfunc()
    for l in f:
        hsh.update(l.encode('utf-8'))

    f.close()
    return hsh.hexdigest()

class YAMLWriter(object):
    def __init__(self, source, prps, is32bit, is_correctness_wit, saveto):
        self._source = source
        self._relsource = relpath(source, dirname(saveto))
        self._prps = prps
        self._is32bit = is32bit
        self._correctness_wit = is_correctness_wit
        self._trivial_target = "reach_error"

        self.test = []
        self.errorLoc = None
        self.errorExpr = None
        self.calls = dict()
        self.witness = []

    def add_metadata(self, version='2.1'):
        witness = {}
        witness['entry_type'] = "violation_sequence" if not self._correctness_wit else "invariant_set"
        witness['metadata'] = {
            'format_version' : version,
            'creation_time' :  '{date:%Y-%m-%dT%T}Z'.format(date=datetime.datetime.utcnow()),
            'producer' : {'name' : 'symbiotic',
                          'version' : get_versions()[0] },
            'uuid' : str(uuid.uuid4()),
            'task' :
                { 'input_files' : [self._relsource],
                  'input_file_hashes' : { self._relsource : get_hash(self._source)},
                  'specification' : ','.join(self._prps.ltl()),
                  'data_model' : "ILP32" if self._is32bit else "LP64",
                  'language' : "C"}
        }
        self.witness.append(witness)


    def generate_violation_witness(self, path):
        """
        Take a .test file generated by a tool and generate a new
        .yml file from it that has all the needed metadata.

        \param path         the .waypoints file
        """

        self.parse(path)
        assert self.errorLoc or self._prps.termination(), "Failed generating a YAML witness"

        self.add_metadata()
        self.create_content()


    def generate_trivial_violation_witness(self, error_location=None):
        """
        Generate a violation witness that contains only the target waypoint.
        Used when the error was found in a program reversed by reverser, where the
        waypoints of the error path do not correspond to the original program
        (so the .waypoints file is not used at all).

        \param error_location  (file, line, column) of the reached error
                                  in the original program, or None
        """
        dbg("generating trivial violation YAML witness")

        self.add_metadata()
        self.create_content(trivial=True, error_location=error_location)

    def generate_concurrent_witness(self, created, error, calls):
        """
        Generate a violation witness of a concurrent program (format 2.2):
        the creations of the threads, then the error, each as (thread, line)
        """
        with open(self._source, errors='replace') as f:
            self._lines = f.read().split('\n')
        self._find_references()
        thread, line = error
        line = self._error_line(line, calls)

        self.add_metadata('2.2')
        content = [[self._waypoint('function_enter', t, l)] for t, l in created]
        content.append([self._waypoint('target', thread, line,
                                       self._column(line, calls))])
        self.witness[0]['content'] = [{'segment' : s} for s in content]

    def _waypoint(self, kind, thread, line, column=None):
        # validators do not match function_enter waypoints with a column
        location = {'file_name' : self._relsource, 'line' : line}
        if column:
            location['column'] = column
        location['function'] = self._function(line)
        return {'waypoint' : {'type' : kind, 'action' : 'follow',
                              'thread_id' : thread, 'location' : location}}

    def _find_references(self):
        """ The definitions of functions and the names used on each line """
        sys.setrecursionlimit(2048)
        index = clang.cindex.Index.create()
        tu = index.parse(self._source, args=['-fbracket-depth=2048'])
        kinds = clang.cindex.CursorKind
        self._functions = []
        self._references = {}
        for node in tu.cursor.walk_preorder():
            if not node.location.file or node.location.file.name != self._source:
                continue
            start, end = node.extent.start, node.extent.end
            if node.kind == kinds.FUNCTION_DECL and node.is_definition():
                self._functions.append((node.spelling, start.line, end.line))
            elif node.kind in (kinds.CALL_EXPR, kinds.DECL_REF_EXPR):
                # the location of a call in a macro is that of the macro
                self._references.setdefault(node.location.line, []).append(
                    (node.spelling, node.location.column))
            elif node.kind == kinds.MEMBER_REF_EXPR:
                self._references.setdefault(node.location.line, []).append(
                    (node.spelling, start.column))

    def _column(self, line, names):
        references = self._references.get(line, [])
        for name in names:
            columns = [c for n, c in references if n == name.split('.')[-1]]
            if columns:
                return min(columns)
        text = self._lines[line - 1]
        return len(text) - len(text.lstrip()) + 1

    def _error_line(self, line, calls):
        """
        CSeq maps a labelled statement to the line before the label, so
        the error is the first error call from the line on in its function
        """
        end = next((end for f, start, end in self._functions
                    if start <= line <= end), line)
        return next((n for n in range(line, end + 1)
                     if any(r in calls for r, c in self._references.get(n, []))),
                    line)

    def _function(self, line):
        return next((f for f, start, end in self._functions
                     if start <= line <= end), None)

    def generate_correctness_witness(self):
        self.add_metadata()

        # So far we can only create trivial correctness witnesses
        self.witness[0]['content'] = []

    def dump(self):
        print(self.witness)

    def write(self, to):
        with open(to, "w") as witness_file:
            yaml.safe_dump(self.witness, witness_file, default_style=None)



    # Traverse the AST, find the right brackets of functions and the full expression of the target
    def traverse_AST(self, node):

        # get infinitely recurring location
        if self._prps.termination() and self.errorLoc and not self.errorExpr:
            self.errorExpr = _get_recurring_location(node, self.errorLoc)

        for child in node.get_children():

            if not child.location.file or child.location.file.name != self._source:
                continue

            start = child.extent.start
            end = child.extent.end

            if child.kind == clang.cindex.CursorKind.CALL_EXPR and (start.line, start.column) in self.calls:
                self.calls[(start.line, start.column)] = end.line, end.column - 1

            if self.errorExpr or not self.errorLoc or not child.kind.is_expression():
                self.traverse_AST(child)
                continue

            # check range of the expression
            err_line = self.errorLoc[0]
            err_col = self.errorLoc[1]
            if not self.errorExpr and location_in_range(err_line, err_col, \
                                                        start.line, start.column, \
                                                        end.line, end.column):
                self.errorExpr = start.line, start.column
            self.traverse_AST(child)


    # Find the first call of the trivial target in the AST
    def AST_find_trivial_target(self, node):
        for child in node.get_children():
            if self.errorExpr:
                return

            if not child.location.file or child.location.file.name != self._source:
                continue

            if child.kind == clang.cindex.CursorKind.CALL_EXPR:
                called = child.referenced
                if called is not None and called.spelling == self._trivial_target:
                    start = child.extent.start
                    self.errorExpr = start.line, start.column
                    return

            self.AST_find_trivial_target(child)



    def create_content(self, trivial=False, error_location=None):
        sys.setrecursionlimit(2048)

        if trivial and error_location is not None:
            # the exact target location is already known (mapped from the concrete
            # value of __reverser_error_id() via reverser's --error-ids file), so
            # there is no need to guess it by scanning the source's AST
            _, line, col = error_location
            self.errorExpr = (line, col)
        else:
            index = clang.cindex.Index.create()
            tu = index.parse(self._source, args=['-fbracket-depth=2048'])
            root = tu.cursor
            if trivial:
                print_stderr("Warning: error location for trivial witness not supplied, "
                             "the witness will contain the first error location found in the AST")
                self.AST_find_trivial_target(root)
            else:
                self.traverse_AST(root)

        if self.errorLoc and not self.errorExpr:
            print_stderr("Warning: Could not get target location for witness")
            self.errorExpr = self.errorLoc

        content = []

        if not trivial:
            for call in self.test:
                new_location = self.calls[(call[0], call[1])]
                assert new_location, "Failed creating witness"

                segment = []
                waypoint = { 'type' : 'function_return',
                            'action' : 'follow',
                            'constraint' : {
                                'format' : 'c_expression',
                                'value' : '\\result == ' + call[2]
                            },
                            'location' : {
                                'file_name' : self._source,
                                'line' : new_location[0],
                                'column' : new_location[1]
                            }

                            }
                segment.append({'waypoint' : waypoint})
                content.append({'segment' : segment})

        if self.errorLoc:
            last_segment = []
            location = { 'file_name' : self._relsource,
                            'line' : self.errorExpr[0],
                            'column' : self.errorExpr[1]
                       }

            if self._prps.termination():
                last = { 'type'       : 'assumption',
                         'action'     : 'cycle',
                         'location'   : location,
                         'constraint' : {
                            'format' : 'c_expression',
                            'value'  : '1'
                          }
                       }
            else:
                last = { 'type'     : 'target',
                         'action'   : 'follow',
                         'location' : location
                       }


            last_segment.append({'waypoint' : last})
            content.append({'segment' : last_segment})

        self.witness[0]['content'] = content


    def parse(self, path):
        with open(path, "r") as testfile:
            cycle = False
            for line in testfile.readlines():
                if line[0] == '@':
                    self.errorLoc = tuple(map(int, line.strip('\n').split(':')[2:]))
                    break
                call = line.strip('\n').split(':')
                line = int(call[1])
                col = int(call[2])
                value = call[3]
                cycle = (len(call) == 5) # is there the cycle flag?
                self.test.append((line, col, value, cycle))
                self.calls[(line, col)] = None

        # No need for this if we have cycle waypoints
        if cycle:
            self.errorLoc = None


def _get_recurring_location(node, error_loc):
    n_start = node.extent.start
    n_end = node.extent.end
    children = list(node.get_children())

    recurring_node = None

    if (node.kind == clang.cindex.CursorKind.FOR_STMT or \
        node.kind == clang.cindex.CursorKind.WHILE_STMT):

        if (error_loc[0] == n_start.line and error_loc[1] == n_start.column) or \
            location_in_range(error_loc[0], error_loc[1],
                              children[0].extent.start.line, children[0].extent.start.column,
                              children[-2].extent.end.line, children[-2].extent.end.column):
            return children[-1].extent.start.line, children[-1].extent.start.column

    if node.kind == clang.cindex.CursorKind.DO_STMT:

        if (error_loc[0] == children[0].extent.end.line and \
           error_loc[1] == children[0].extent.end.column - 1) or \
           location_in_range(error_loc[0], error_loc[1],
                            children[1].extent.start.line, children[1].extent.start.column,
                            children[1].extent.end.line, children[1].extent.end.column):
            return children[0].extent.start.line, children[0].extent.start.column

    if node.kind == clang.cindex.CursorKind.IF_STMT:

        if (error_loc[0] == children[0].extent.start.line and \
           error_loc[1] == children[0].extent.start.column) or \
           location_in_range(error_loc[0], error_loc[1],
                             children[0].extent.start.line, children[0].extent.start.column,
                             children[0].extent.end.line, children[0].extent.end.column):
            return n_start.line, n_start.column

    if node.kind == clang.cindex.CursorKind.SWITCH_STMT and \
       error_loc[0] == n_start.line and \
       error_loc[1] == n_start.column:
        return n_start.line, n_start.column

    if (node.kind.is_statement() or node.kind.is_declaration()) and \
        error_loc[0] == n_start.line and \
        error_loc[1] == n_start.column:
         return n_start.line, n_start.column

def location_in_range(line, col, startline, startcol, endline, endcol):

    if startline > line or endline < line:
        return False

    if startline == line and startcol > col:
        return False

    if endline == line and endcol < col:
        return False

    return True
